import { existsSync, readFileSync, writeFileSync } from 'node:fs'

const LOCAL_MARKER = '# generated by scripts/wt-worktree-env.mjs'

const [project] = process.argv.slice(2)

if (!project) {
  console.error('usage: wt-worktree-env.mjs <compose-project>')
  process.exit(1)
}

const raw = readFileSync('.env', 'utf8')

const read = (key, fallback) => {
  const match = new RegExp(`^${key}=(.*)$`, 'm').exec(raw)
  return match ? match[1].trim() : fallback
}

const serviceHost = (service) => `${service}.${project}.orb.local`
const appUrl = `http://${serviceHost('app')}`

const overrides = {
  COMPOSE_PROJECT_NAME: project,
  APP_URL: appUrl,
  APP_ALLOWED_ORIGINS: appUrl,
  DATABASE_URL: `postgres://${read('POSTGRES_USER', 'postgres')}:${read('POSTGRES_PASSWORD', 'postgres')}@${serviceHost('postgres')}:5432/${read('POSTGRES_DB', 'open-mercato')}`,
  DOCUMENTS_COLLAB_REDIS_URL: `redis://${serviceHost('redis')}:6379`,
  MEILISEARCH_HOST: `http://${serviceHost('meilisearch')}:7700`,
}

const applied = new Set()
const lines = raw.split('\n').map((line) => {
  const key = /^([A-Z0-9_]+)=/.exec(line)?.[1]
  if (!key || !(key in overrides)) return line
  applied.add(key)
  return `${key}=${overrides[key]}`
})

while (lines.length && lines[lines.length - 1].trim() === '') lines.pop()

const missing = Object.entries(overrides).filter(([key]) => !applied.has(key))
if (missing.length) {
  lines.push('', `# worktree overrides (${project})`, ...missing.map(([key, value]) => `${key}=${value}`))
}

writeFileSync('.env', `${lines.join('\n')}\n`)

const localPath = '.env.local'
const localExists = existsSync(localPath)
const localIsOurs = localExists && readFileSync(localPath, 'utf8').startsWith(LOCAL_MARKER)

if (!localExists || localIsOurs) {
  writeFileSync(localPath, [
    `${LOCAL_MARKER} for ${project}`,
    `APP_URL=${appUrl}`,
    'APP_ALLOWED_ORIGINS=**.orb.local',
    `DOCUMENTS_COLLAB_ALLOWED_ORIGINS=${appUrl}`,
    '',
    '# No outbound email provider module is enabled in a dev worktree, so every',
    '# notification that would be emailed - a role assignment, a user invite - throws',
    '# EMAIL_TRANSPORT_NOT_CONFIGURED and surfaces as a runtime error in the dev',
    '# overlay. The operation itself still succeeds and the in-app notification still',
    '# lands. Drop this line to exercise real email delivery.',
    'OM_DISABLE_EMAIL_DELIVERY=1',
    '',
    '# Print the seeded demo warehouseman on the panel login page. Refused outright',
    '# when NODE_ENV is production, so this can only ever advertise a throwaway',
    '# environment. Drop the line to hide the box.',
    'OM_SHOW_DEMO_CREDENTIALS=1',
    '',
  ].join('\n'))
} else {
  console.warn(`${localPath} is hand-edited — left untouched; APP_URL must be ${appUrl}`)
}

console.log(`.env + .env.local pinned to ${project} — app at ${appUrl}`)
